#!/usr/bin/env python3
"""Regenerate the PostgreSQL DDL and the Alembic initial revision from the models.

    cd rs-ai-trader
    python scripts/generate_schema.py

Source of truth is ``backend/app/db/models.py``. Running this keeps
``database/schema.sql`` (used by docker-compose as the Postgres init script) and
``database/migrations/versions/0001_initial.py`` in sync with the ORM.
"""
from __future__ import annotations

import pathlib
import sys
from datetime import datetime, timezone

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from sqlalchemy.dialects import postgresql  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from app.db import models as _models  # noqa: F401,E402  (registers the tables)
from app.db.base import Base  # noqa: E402

SCHEMA_PATH = ROOT / "database" / "schema.sql"
MIGRATION_PATH = ROOT / "database" / "migrations" / "versions" / "0001_initial.py"

HEADER = """-- =====================================================================
-- RS AI TRADER - PostgreSQL schema (generated, do not hand-edit)
--
--   python scripts/generate_schema.py
--
-- Source of truth: backend/app/db/models.py (SQLAlchemy 2.0).
-- This file is used by docker-compose as a Postgres init script and is the
-- readable reference for reviewers. Applying migrations with Alembic is the
-- supported upgrade path for existing databases:
--
--   cd backend && alembic -c alembic.ini upgrade head
-- =====================================================================
"""


def build_statements() -> tuple[list[str], list[str]]:
    dialect = postgresql.dialect()
    statements: list[str] = []
    for table in Base.metadata.sorted_tables:
        statements.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";")
        for index in sorted(table.indexes, key=lambda i: i.name or ""):
            statements.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";")
    tables = [table.name for table in Base.metadata.sorted_tables]
    return statements, tables


def write_schema(statements: list[str]) -> None:
    out = [HEADER, f"-- {len(Base.metadata.tables)} tables, {len(statements)} statements\n", "BEGIN;\n"]
    for statement in statements:
        out.append(statement + "\n")
    out.append("COMMIT;\n")
    SCHEMA_PATH.write_text("\n".join(out))
    print(f"wrote {SCHEMA_PATH.relative_to(ROOT)} ({len(statements)} statements)")


def write_migration(statements: list[str], tables: list[str]) -> None:
    lines = [
        '"""initial schema',
        "",
        "Revision ID: 0001_initial",
        f"Created: {datetime.now(timezone.utc).date().isoformat()}",
        "",
        "Generated by scripts/generate_schema.py from app/db/models.py.",
        '"""',
        "from __future__ import annotations",
        "",
        "from alembic import op",
        "",
        "revision = \"0001_initial\"",
        "down_revision = None",
        "branch_labels = None",
        "depends_on = None",
        "",
        "",
        "STATEMENTS = [",
    ]
    for statement in statements:
        # Alembic's op.execute() adds no terminator; strip the SQL ";" we keep
        # for the human-readable schema.sql so we never emit ";;".
        lines.append(f"    {statement.rstrip().rstrip(';')!r},")
    lines += [
        "]",
        "",
        "",
        "TABLES = [",
    ]
    for table in reversed(tables):
        lines.append(f"    {table!r},")
    lines += [
        "]",
        "",
        "",
        "def upgrade() -> None:",
        "    for statement in STATEMENTS:",
        "        op.execute(statement)",
        "",
        "",
        "def downgrade() -> None:",
        "    # Reverse dependency order so foreign keys drop cleanly.",
        "    for table in TABLES:",
        "        op.execute(f'DROP TABLE IF EXISTS {table} CASCADE')",
        "",
    ]
    MIGRATION_PATH.parent.mkdir(parents=True, exist_ok=True)
    MIGRATION_PATH.write_text("\n".join(lines))
    print(f"wrote {MIGRATION_PATH.relative_to(ROOT)}")


def main() -> None:
    statements, tables = build_statements()
    write_schema(statements)
    write_migration(statements, tables)
    print(f"{len(Base.metadata.tables)} tables / {len(statements)} statements")


if __name__ == "__main__":
    main()
