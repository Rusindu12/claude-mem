// Exercise the actual bundled paper-account functions without a browser.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname, '../app/src/main/assets/index.html'), 'utf8');
const start = html.indexOf('const FEE_RATE =');
const end = html.indexOf('function checkPaperPositions', start);
assert.ok(start >= 0 && end > start);
const context = { state: { paper: {bal: 10000, positions: [], history: [], day: 'today', dayPnl: 0, seq: 1}, tickers: {} }, dayKey: () => 'today', now: () => 0, save: () => {} };
vm.createContext(context);
vm.runInContext(html.slice(start, end), context);
const close = (x, y) => assert.ok(Math.abs(x-y) < 1e-8, `${x} != ${y}`);
assert.equal(context.openPaper('BTCUSDT', 100, -1, 0, 0, 'manual', 1).error, 'invalid amount');
const opened = context.openPaper('BTCUSDT', 100, 1000, 5, 2, 'manual', 1);
assert.ok(opened.ok);
close(context.state.paper.bal, 8999);
const part = context.closePaper(opened.pos.id, 110, 'partial', 4);
close(part.pnl, 39.16);
close(opened.pos.qty, 6);
close(opened.pos.entry, 100);
close(opened.pos.tp, 105);
close(context.state.paper.dayPnl, 39.16);
const final = context.closePaper(opened.pos.id, 110, 'rest');
close(final.pnl, 58.74);
close(context.state.paper.bal, 10097.9);
assert.equal(context.state.paper.positions.length, 0);
assert.equal(context.openPaper('BTCUSDT', 100, 20000, 0, 0, 'bot', -1).error, 'insufficient');
console.log('Paper account partial-close and validation checks passed.');
// Limit sells must close partial quantities instead of silently reporting full fills.
const limitStart = html.indexOf('function checkPaperLimitOrders()');
const limitEnd = html.indexOf('/* ============================================================================', limitStart);
Object.assign(context, { t: x => x, notify: () => {}, toast: () => {}, paintTrade: () => {}, fmtQty: String, fmtPrice: String });
vm.runInContext(html.slice(limitStart, limitEnd), context);
const second = context.openPaper('BTCUSDT', 100, 1000, 0, 0, 'manual', 1);
context.state.tickers.BTCUSDT = {last: 110};
context.state.paper.orders = [{id: 'limit-1', sym: 'BTCUSDT', side: 'SELL', qty: 3, price: 105, closeLong: true}];
context.checkPaperLimitOrders();
close(second.pos.qty, 7);
assert.equal(context.state.paper.orders.length, 0);
console.log('Paper limit-sell partial-fill check passed.');
