const assert = require('node:assert/strict');
const fs = require('node:fs');
const app = fs.readFileSync(new URL('../app/src/app.js', `file://${__filename}`), 'utf8');
const native = fs.readFileSync(new URL('../android/src/lk/cryptoai/pro/MainActivity.java', `file://${__filename}`), 'utf8');
const html = fs.readFileSync(new URL('../app/index.html', `file://${__filename}`), 'utf8');
assert.match(app, /tf:'1m'/, 'bot defaults to 1-minute closed candles');
assert.match(app, /setInterval\(\(\)=>botTick\(\),60000\)/, 'bot scan cadence is one minute');
assert.match(app, /openConfirm\('Arm LIVE auto-trading'/, 'live mode requires an explicit arming confirmation');
assert.match(app, /free\*\.10/, 'each live order is capped at 10% of free quote balance');
assert.match(app, /orderList\/oco/, 'live entry attempts exchange-side OCO protection');
assert.match(app, /emergency market sell attempted/, 'OCO failure has a guarded emergency-exit path');
assert.match(app, /Stale ticker feed; live entries paused/, 'stale prices prevent new live entries');
assert.match(app, /Existing '\+base\+' balance detected/, 'bot refuses to take over existing coin balances');
assert.match(native, /api\/v3\/orderList\/oco/, 'native allowlist includes OCO creation');
assert.match(native, /api\/v3\/openOrders/, 'native allowlist includes open-order reconciliation');
assert.match(native, /api\/v3\/orderList"\) && !m\.equals\("DELETE"\)/, 'OCO cancel is restricted to DELETE');
assert.doesNotMatch(native, /api\/v3\/withdraw/, 'withdrawal paths are not in the native API bridge');
assert.match(html, /id="botExec"/, 'the UI exposes paper/live execution selection');
assert.match(html, /id="livePosList"/, 'the UI exposes bot-managed OCO positions');
console.log('Auto-live safety guards: OK');
